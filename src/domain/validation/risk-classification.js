/* =========================================================================
   Phase 3A-3 — Canonical risk classification (shared by client AND server)
   ---------------------------------------------------------------------------
   Pure domain module. No DOM, no Firestore, no clock, no I/O, never throws.
   The browser (alert center / metric guard) and the Cloud Function that approves
   an opportunity BOTH call classifyOpportunity(d, c) on the same code, copied
   byte-for-byte into functions/generated by scripts/build-domain.cjs. There is
   no second implementation to drift.

   Inputs: d = withDefaults(opportunity), c = compute(d)   (same on both sides)

   Colour contract (decided by the owner, 3A-3):
     red     INVALID / INCOMPLETE / classification error   -> blocks approval
     yellow  WARNINGS, or any financial high-risk reason    -> never blocks alone
     green   OK

   Compound warnings (decision 6, option B): when the number of financial
   high-risk reasons reaches COMPOUND_WARNING_THRESHOLD, approval is not blocked
   but requires a written acknowledgement that the server records.

   Only FINANCIAL high-risk reasons live here (they are a function of d and c).
   Contextual reasons that need data outside one opportunity (risk register,
   portfolio concentration) stay in the UI and never influence the colour or
   the server decision.
   ========================================================================= */
import { validateOpportunity, STATUS } from './input-validation-engine.js';
import { debtCoverageByYear } from './debt-coverage.js';

export const COLOR = Object.freeze({ RED: 'red', YELLOW: 'yellow', GREEN: 'green' });

/* WARNING paths that count as a high-risk reason when flagged UNUSUALLY_HIGH. */
export const HIGH_RISK_PATHS = Object.freeze([
  'financing.ltc', 'financing.saibor', 'financing.margin', 'development.constructionYears', 'development.exitCapRate',
]);

/* Construction-phase interest funded by equity by design is a note, not a risk flag. */
export const COUNT_CONSTRUCTION_SHORTFALL_AS_RISK = false;

/* Number of financial high-risk reasons at which approval needs a written acknowledgement.
   Owner decision (3A-3 follow-up): 2 — two simultaneous high-risk reasons in different fields are already a
   real signal. Measured on the 34 reference fixtures: none has 2+, so this adds no friction to them. */
export const COMPOUND_WARNING_THRESHOLD = 2;

export const isBlockedStatus = (status) => status === 'ERROR' || status === STATUS.INVALID || status === STATUS.INCOMPLETE;

function emptyDebt() {
  return { ok: false, hasDebtService: false, riskShort: [], conShort: [], worst: null };
}

/**
 * Classify one opportunity. Never throws: any internal failure is reported as
 * status 'ERROR' / colour red (fail-closed).
 */
export function classifyOpportunity(d, c) {
  try {
    const report = validateOpportunity(d, c);
    const status = report.status;
    const blocked = isBlockedStatus(status);
    const reasons = [];

    report.warnings.forEach((w) => {
      if (w.code === 'UNUSUALLY_HIGH' && HIGH_RISK_PATHS.includes(w.path)) {
        reasons.push({ code: 'HIGH_RISK_PARAM', path: w.path, ar: w.messageAr, en: w.messageEn });
      }
      if (w.code === 'OUTPUT_VERY_HIGH_IRR') {
        reasons.push(blocked
          ? { code: 'VERY_HIGH_IRR', path: w.path, ar: 'العائد المحسوب مرتفع جدًا — راجع الافتراضات.', en: 'The computed return is very high — review the assumptions.' }
          : { code: 'VERY_HIGH_IRR', path: w.path, ar: w.messageAr, en: w.messageEn });
      }
    });

    /* Year-by-year debt coverage: in any year with debt service, cash available
       (NOI + net sale proceeds) below the debt service is a risk. */
    let debt = emptyDebt();
    try {
      const dc = debtCoverageByYear(c);
      const opShort = dc.shortfalls.filter((y) => y.phase !== 'construction');
      const conShort = dc.shortfalls.filter((y) => y.phase === 'construction');
      const riskShort = COUNT_CONSTRUCTION_SHORTFALL_AS_RISK ? dc.shortfalls : opShort;
      debt = { ok: true, hasDebtService: !!dc.hasDebtService, riskShort, conShort, worst: dc.worst || null };
      if (riskShort.length) {
        const worst = riskShort.reduce((a, b) => (b.ratio < a.ratio ? b : a));
        const yrs = riskShort.map((y) => y.yr).join('، ');
        const yrsEn = riskShort.map((y) => y.yr).join(', ');
        const fig = blocked ? '' : ` (الأدنى ${worst.ratio.toFixed(2)}×)`;
        const figEn = blocked ? '' : ` (lowest ${worst.ratio.toFixed(2)}×)`;
        reasons.push({
          code: 'DEBT_SHORTFALL', path: 'debtService', years: riskShort.map((y) => y.yr),
          ar: `التدفق المتاح لسداد الدين (تشغيل + مبيعات) أقل من خدمة الدين في السنوات ${yrs}${fig}.`,
          en: `Cash available for debt service (operations + sales) is below the debt service in year(s) ${yrsEn}${figEn}.`,
        });
      }
    } catch (e) { debt = emptyDebt(); }

    const color = blocked ? COLOR.RED
      : (status === STATUS.WARNINGS || reasons.length > 0) ? COLOR.YELLOW : COLOR.GREEN;
    const count = reasons.length;
    return {
      status, color, blocked, error: null, report,
      highRisk: { flag: reasons.length > 0, reasons },
      debt,
      compound: { count, threshold: COMPOUND_WARNING_THRESHOLD, requiresAcknowledgement: !blocked && count >= COMPOUND_WARNING_THRESHOLD },
      /* Figure-free, serialisable summary for audit trails and server responses. */
      issueCodes: []
        .concat(report.blocking.map((i) => ({ severity: i.severity, path: i.path, code: i.code })))
        .concat(report.incomplete.map((i) => ({ severity: i.severity, path: i.path, code: i.code })))
        .concat(report.warnings.map((i) => ({ severity: i.severity, path: i.path, code: i.code }))),
      highRiskCodes: reasons.map((r) => ({ code: r.code, path: r.path })),
    };
  } catch (e) {
    return {
      status: 'ERROR', color: COLOR.RED, blocked: true, error: String((e && e.message) || e), report: null,
      highRisk: { flag: false, reasons: [] }, debt: emptyDebt(),
      compound: { count: 0, threshold: COMPOUND_WARNING_THRESHOLD, requiresAcknowledgement: false },
      issueCodes: [], highRiskCodes: [],
    };
  }
}

/** Serialisable, figure-free verdict stored in audit records and returned by the server. */
export function verdictSummary(cls) {
  return {
    status: cls.status,
    color: cls.color,
    blocked: cls.blocked,
    highRisk: cls.highRisk.flag,
    highRiskCodes: cls.highRiskCodes,
    issueCodes: cls.issueCodes,
    compound: { count: cls.compound.count, threshold: cls.compound.threshold, requiresAcknowledgement: cls.compound.requiresAcknowledgement },
  };
}
